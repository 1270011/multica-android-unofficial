/**
 * Expo config plugin: Android network security config.
 *
 * Android 7+ trusts only the system CA store for apps by default. Self-hosted
 * Multica servers often terminate TLS with a certificate from a private CA,
 * so the "Local / VPN" connection mode needs the app
 * to also trust CAs the user installed on the phone. This plugin writes
 * `res/xml/network_security_config.xml` with `system` + `user` trust
 * anchors and points the manifest at it. Cleartext HTTP stays disabled.
 *
 * Decision: user-installed CAs instead of bundling / importing a
 * PEM in the app — no CA material in the APK, no custom TLS code, and a
 * CA rotation only needs a new certificate on the phone, not a new build.
 */
const fs = require("node:fs");
const path = require("node:path");
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

const XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-network-security.js (expo prebuild). -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false">
    <trust-anchors>
      <certificates src="system" />
      <certificates src="user" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

function withAndroidNetworkSecurity(config) {
  config = withDangerousMod(config, [
    "android",
    async (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, "app/src/main/res/xml");
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, "network_security_config.xml"), XML);
      return c;
    },
  ]);
  config = withAndroidManifest(config, (c) => {
    const app = c.modResults.manifest.application?.[0];
    if (app) {
      app.$["android:networkSecurityConfig"] = "@xml/network_security_config";
    }
    return c;
  });
  return config;
}

module.exports = withAndroidNetworkSecurity;
